#!/usr/bin/env python3
"""Generate res/values/strings.xml (English) and res/values-ru/strings.xml from tools/strings_table.py."""
import os
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings_table import STRINGS  # noqa: E402

RES = os.path.join(HERE, "..", "android", "app", "src", "main", "res")


def enc(text):
    s = escape(text)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def write(folder, idx):
    d = os.path.join(RES, folder)
    os.makedirs(d, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py from tools/strings_table.py. Do not edit. -->", "<resources>"]
    for row in STRINGS:
        key, text = row[0], row[idx]
        extra = ' translatable="false"' if key in ("app_name", "thumb_service_label") and False else ""
        lines.append('    <string name="%s"%s>%s</string>' % (key, extra, enc(text)))
    lines.append("</resources>")
    with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    write("values", 1)
    write("values-ru", 2)
    print("wrote %d strings x 2 languages" % len(STRINGS))
